#!/usr/bin/env python3
"""Prepare the AirScript 1.0 data-table type declaration.

Source: https://www.npmjs.com/package/wps-airscript-types (MIT, happyuz)
        types/ApiV1.d.ts

The upstream file cannot be compiled as-is:
  * `interface Record` shadows TypeScript's built-in `Record<K, V>`;
  * `enum ESaveResult` and `namespace Enum` lack a `declare` modifier;
  * `Buffer` and `URL` are referenced but never declared;
  * the JSDoc comments are double-encoded (UTF-8 read as GBK), so some
    newlines were replaced by `?`, which breaks block comments and makes
    tsc report TS1046 for the following declaration.

We therefore strip comments, rename `Record` to `DBRecord`, and prepend
minimal ambient declarations.  Run after unpacking the npm tarball:

    npm pack wps-airscript-types@1.0.0
    tar -xzf wps-airscript-types-1.0.0.tgz
    python tools/prepare_databook.py \
        --src package/types/ApiV1.d.ts \
        --out extension/types/databook/ApiV1.d.ts
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

HEADER = """/*!
 * AirScript 1.0 data-table / worksheet type declarations.
 *
 * Source: wps-airscript-types@1.0.0 (https://www.npmjs.com/package/wps-airscript-types)
 * MIT License, Copyright (c) happyuz
 *
 * Generated by tools/prepare_databook.py. Do not edit by hand.
 * Upstream comments were removed because they are double-encoded and break tsc.
 */

type URL = string;

interface Buffer {
  toString(encoding?: string): string;
}

"""


def clean(source: str) -> str:
    # The upstream comments are corrupted; dropping them also removes the
    # stray `*/`/`?` sequences that make tsc treat declarations as top-level.
    text = re.sub(r"/\*.*?\*/", "", source, flags=re.S)
    text = re.sub(r"//.*$", "", text, flags=re.M)

    # `Record` is a built-in utility type; keep the public property name but
    # rename the interface so the two do not collide.
    text = text.replace("interface Record {", "interface DBRecord {")
    text = text.replace("  Record: Record;", "  Record: DBRecord;")

    text = text.replace("enum ESaveResult {", "declare enum ESaveResult {")
    text = text.replace("namespace Enum {", "declare namespace Enum {")
    return HEADER + text.lstrip()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--src", required=True, type=Path, help="upstream types/ApiV1.d.ts")
    parser.add_argument("--out", required=True, type=Path, help="output path")
    args = parser.parse_args()

    source = args.src.read_text(encoding="utf-8")
    result = clean(source)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(result, encoding="utf-8")
    print(f"wrote {args.out} ({len(result)} chars, {len(result.encode('utf-8'))} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
